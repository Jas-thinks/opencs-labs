#!/usr/bin/env python3
"""Render every node's configuration from inventory.json + secrets.

    python3 deploy/distributed/render.py            # writes deploy/distributed/build/

Inputs
    inventory.json            topology (committed, no secrets)
    secrets/cluster.env       generated on first run (gitignored): JWT secret,
                              DB/replication passwords, per-shard Hub tokens,
                              crypt keys and cookie secrets
Outputs (gitignored, mode 0600)
    build/ssh_config          `ssh -F build/ssh_config <alias>`
    build/<alias>/...         files copied verbatim to ~/opencs/env/ on that node

Standard library only, so it runs on any operator machine.
"""

from __future__ import annotations

import base64
import json
import os
import secrets
import stat
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
BUILD = HERE / "build"
SECRETS = HERE / "secrets" / "cluster.env"
HOME = "/home/student"
ROOT = f"{HOME}/opencs"
KEY = Path.home() / ".ssh" / "opencs_deploy_ed25519"


# --------------------------------------------------------------------------- #
# secrets
# --------------------------------------------------------------------------- #
def load_or_create_secrets(shards: int) -> dict[str, str]:
    values: dict[str, str] = {}
    if SECRETS.exists():
        for line in SECRETS.read_text().splitlines():
            if "=" in line and not line.startswith("#"):
                k, v = line.split("=", 1)
                values[k] = v
    wanted = {
        "JWT_SECRET": lambda: secrets.token_hex(32),
        "DB_PASSWORD": lambda: secrets.token_hex(24),
        "REPL_PASSWORD": lambda: secrets.token_hex(24),
    }
    for i in range(shards):
        wanted[f"HUB_TOKEN_{i}"] = lambda: secrets.token_hex(32)
        wanted[f"HUB_CRYPT_KEY_{i}"] = lambda: base64.urlsafe_b64encode(os.urandom(32)).decode()
        wanted[f"HUB_COOKIE_SECRET_{i}"] = lambda: secrets.token_hex(32)
        wanted[f"CHP_TOKEN_{i}"] = lambda: secrets.token_hex(32)
    changed = False
    for key, make in wanted.items():
        if not values.get(key):
            values[key] = make()
            changed = True
    if changed:
        SECRETS.parent.mkdir(parents=True, exist_ok=True)
        SECRETS.write_text(
            "# Generated by render.py. Never commit. Rotating JWT_SECRET logs everyone out;\n"
            "# rotating a HUB_TOKEN requires restarting that Hub and every API node.\n"
            + "".join(f"{k}={v}\n" for k, v in values.items())
        )
        SECRETS.chmod(stat.S_IRUSR | stat.S_IWUSR)
    return values


# --------------------------------------------------------------------------- #
# helpers
# --------------------------------------------------------------------------- #
def write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content)
    path.chmod(stat.S_IRUSR | stat.S_IWUSR)


def env_file(pairs: dict[str, str | int]) -> str:
    """bash-sourceable KEY='value' lines (single-quoted: JSON-safe)."""
    lines = ["# Rendered by deploy/distributed/render.py - do not edit on the node.\n"]
    for k, v in pairs.items():
        s = str(v)
        if "'" in s:
            raise ValueError(f"{k} contains a single quote")
        lines.append(f"{k}='{s}'\n")
    return "".join(lines)


def by_role(nodes: list[dict], role: str) -> list[dict]:
    return [n for n in nodes if n["role"] == role]


# --------------------------------------------------------------------------- #
# per-role configuration
# --------------------------------------------------------------------------- #
def shard_config(inv: dict, sec: dict) -> list[dict]:
    out = []
    for n in sorted(by_role(inv["nodes"], "hub"), key=lambda n: n["shard"]):
        i = n["shard"]
        mapped = f"http://{n['host']}:{n['public_port']}/nb/{i}"
        out.append(
            {
                "name": f"nb{i}",
                # Backend -> Hub goes straight to the shard's mapped port (no edge hop).
                "api_url": f"{mapped}/hub/api",
                "proxy_url": mapped,
                # Browser -> notebook goes through the edge: same origin as the app.
                "public_url": f"{inv['public_origin']}/nb/{i}",
                "api_token": sec[f"HUB_TOKEN_{i}"],
            }
        )
    return out


def app_env(inv: dict, sec: dict, node: dict, *, worker: bool) -> dict[str, str | int]:
    t = inv["tuning"]
    pg = by_role(inv["nodes"], "pg-primary") + by_role(inv["nodes"], "pg-standby")
    hosts = "&".join(f"host={n['ip']}:5432" for n in pg)
    origins = [inv["public_origin"], inv["standby_origin"]]
    datasets = f"{ROOT}/datasets/serving"
    return {
        "OPENCE_ENV": "development",  # no TLS + dev auth: production mode refuses both
        "OPENCE_NODE_NAME": node["name"],
        "OPENCE_NODE_ROLE": "worker" if worker else "backend",
        "OPENCE_JWT_SECRET": sec["JWT_SECRET"],
        "OPENCE_JWT_ISSUER": "opencs",
        "OPENCE_SESSION_COOKIE": "opencs_session",
        "OPENCE_COOKIE_SECURE": "false",
        # libpq multi-host: after a standby promotion the pool reconnects to
        # whichever host accepts writes - no config change.
        "OPENCE_DATABASE_URL": (
            f"postgresql+psycopg://opencs:{sec['DB_PASSWORD']}@/opencs?{hosts}"
            "&target_session_attrs=read-write&connect_timeout=2"
        ),
        "OPENCE_DB_POOL_SIZE": t["db_pool_size"],
        "OPENCE_DB_MAX_OVERFLOW": t["db_max_overflow"],
        "OPENCE_PUBLIC_ORIGIN": inv["public_origin"],
        "OPENCE_API_PREFIX": "/api/v1",
        "OPENCE_CORS_ORIGINS": ",".join(origins),
        "OPENCE_AUTH_MODE": "dev",
        "OPENCE_NOTEBOOK_BACKEND": "hub",
        "OPENCE_JUPYTERHUB_SHARDS": json.dumps(shard_config(inv, sec), separators=(",", ":")),
        "OPENCE_DATASET_SERVING_DIR": datasets,
        "OPENCE_DATASET_MOUNT_PATH": datasets,
        "OPENCE_ENVIRONMENT_IMAGE": "host-venv",
        "OPENCE_GRADER": "local",
        "OPENCE_GRADE_RUNNER_PATH": f"{ROOT}/current/notebook-image/grade_runner.py",
        "OPENCE_LOCAL_NOTEBOOK_PYTHON": f"{ROOT}/nb-venv/bin/python",
        "OPENCE_RATE_LIMIT_ENABLED": "true",
        "OPENCE_MAX_ACTIVE_SESSIONS": t["max_active_sessions"],
        # Exactly one process runs the outbox poller and autosave watcher.
        "OPENCE_BACKGROUND_WORKERS_ENABLED": "true" if worker else "false",
        "OPENCE_BACKEND_HOST": "127.0.0.1" if worker else "0.0.0.0",
        "OPENCE_BACKEND_PORT": t["api_port"],
        "OPENCE_RUNTIME_DIR": ROOT,
    }


