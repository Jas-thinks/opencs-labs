import { useCallback, useEffect, useRef, useState } from "react";
import { useNavigate } from "react-router-dom";
import { api } from "../../api/client";
import type { NotificationOut } from "../../api/types";
import { relativeTime } from "../../components/kit";

const POLL_MS = 60_000;

/**
 * Unread badge + dropdown. Polls a cheap indexed count every 60 s while the
 * tab is visible (no WebSockets; ADR-010).
 */
export function NotificationBell() {
  const navigate = useNavigate();
  const [unread, setUnread] = useState(0);
  const [open, setOpen] = useState(false);
  const [items, setItems] = useState<NotificationOut[] | null>(null);
  const ref = useRef<HTMLDivElement>(null);

  const refreshCount = useCallback(async () => {
    if (document.visibilityState !== "visible") return;
    try {
      setUnread((await api.notificationCount()).unread);
    } catch {
      // Transient errors must not break the shell; the next tick retries.
    }
  }, []);

  useEffect(() => {
    void refreshCount();
    const timer = window.setInterval(refreshCount, POLL_MS);
    document.addEventListener("visibilitychange", refreshCount);
    return () => {
      window.clearInterval(timer);
      document.removeEventListener("visibilitychange", refreshCount);
    };
  }, [refreshCount]);

  useEffect(() => {
    if (!open) return;
    const onDown = (event: MouseEvent) => {
      if (ref.current && !ref.current.contains(event.target as Node)) setOpen(false);
    };
    document.addEventListener("mousedown", onDown);
    return () => document.removeEventListener("mousedown", onDown);
  }, [open]);

  async function toggle() {
    const next = !open;
    setOpen(next);
    if (next) {
      try {
        setItems((await api.notifications({ limit: 15 })).notifications);
      } catch {
        setItems([]);
      }
    }
  }

  async function openItem(item: NotificationOut) {
    setOpen(false);
    if (!item.read_at) {
      try {
        setUnread((await api.markNotificationsRead([item.id])).unread);
      } catch {
        /* ignore */
      }
    }
    // Links are in-app routes generated by the server; never external.
    if (item.link.startsWith("/")) navigate(item.link);
  }

  return (
    <div className="bell" ref={ref}>
      <button className="btn btn-ghost btn-sm bell-button" type="button" onClick={toggle} aria-label={`Notifications (${unread} unread)`}>
        <span aria-hidden>🔔</span>
        {unread > 0 && <span className="bell-count">{unread > 99 ? "99+" : unread}</span>}
      </button>
      {open && (
        <div className="bell-menu card" role="menu">
          <div className="spread" style={{ padding: "4px 4px 8px" }}>
            <strong style={{ fontSize: 14 }}>Notifications</strong>
            {unread > 0 && (
              <button
                className="btn btn-ghost btn-sm"
                type="button"
                onClick={async () => {
                  setUnread((await api.markNotificationsRead()).unread);
                  setItems((cur) => cur?.map((n) => ({ ...n, read_at: n.read_at ?? new Date().toISOString() })) ?? null);
                }}
              >
                Mark all read
              </button>
            )}
          </div>
          {items === null && <div className="small dim" style={{ padding: 8 }}>Loading…</div>}
          {items?.length === 0 && <div className="small dim" style={{ padding: 8 }}>You are all caught up.</div>}
          {items?.map((item) => (
            <button key={item.id} type="button" role="menuitem" className={`bell-item${item.read_at ? "" : " unread"}`} onClick={() => openItem(item)}>
              <span>{item.title}</span>
              <span className="small dim">{relativeTime(item.created_at)}</span>
            </button>
          ))}
        </div>
      )}
    </div>
  );
}
